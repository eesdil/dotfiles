hi("BufferLineBufferSelected", { fg = sel_fg, bg = sel_bg, bold = true, italic = true })
hi("BufferLineTab", { fg = dim, bg = bg })
hi("BufferLineTabSelected", { fg = sel_fg, bg = sel_bg, bold = true })
hi("BufferLineTabClose", { fg = dim, bg = bg })
hi("BufferLineCloseButton", { fg = dim, bg = bg })
hi("BufferLineCloseButtonVisible", { fg = dim, bg = bg })
hi("BufferLineCloseButtonSelected", { fg = sel_fg, bg = sel_bg })
hi("BufferLineSeparator", { fg = bg, bg = bg })
hi("BufferLineSeparatorVisible", { fg = bg, bg = bg })
hi("BufferLineSeparatorSelected", { fg = sel_bg, bg = sel_bg })
hi("BufferLineIndicatorSelected", { fg = sel_fg, bg = sel_bg })
hi("BufferLineIndicatorVisible", { fg = dim, bg = bg })
hi("BufferLineModified", { fg = dim, bg = bg })
hi("BufferLineModifiedVisible", { fg = dim, bg = bg })
hi("BufferLineModifiedSelected", { fg = sel_fg, bg = sel_bg })
hi("BufferLineDuplicate", { fg = comment, bg = bg, italic = true })
hi("BufferLineDuplicateVisible", { fg = comment, bg = bg, italic = true })
hi("BufferLineDuplicateSelected", { fg = sel_fg, bg = sel_bg, italic = true })
hi("BufferLineNumbers", { fg = dim, bg = bg })
hi("BufferLineNumbersVisible", { fg = dim, bg = bg })
hi("BufferLineNumbersSelected", { fg = sel_fg, bg = sel_bg, bold = true })
hi("BufferLineErrorSelected", { fg = sel_fg, bg = sel_bg, bold = true })
hi("BufferLineErrorDiagnosticSelected", { fg = sel_fg, bg = sel_bg })
hi("BufferLineWarningSelected", { fg = sel_fg, bg = sel_bg, bold = true })
hi("BufferLineWarningDiagnosticSelected", { fg = sel_fg, bg = sel_bg })
hi("BufferLineInfoSelected", { fg = sel_fg, bg = sel_bg })
hi("BufferLineInfoDiagnosticSelected", { fg = sel_fg, bg = sel_bg })
hi("BufferLineHintSelected", { fg = sel_fg, bg = sel_bg })
hi("BufferLineHintDiagnosticSelected", { fg = sel_fg, bg = sel_bg })
hi("DiagnosticError", { fg = "${THEME_color1}" })
hi("DiagnosticWarn", { fg = dim })
hi("DiagnosticInfo", { fg = accent })
hi("DiagnosticHint", { fg = bright })
hi("DiffAdd", { fg = bright })
hi("DiffChange", { fg = dim })
hi("DiffDelete", { fg = "${THEME_color1}" })
hi("DiffText", { fg = accent, bold = true })
${solid_block}
EOF
  theme_log "wrote $dest"
}

apply() {
  local id="$1"
  local dest="$HOME/.config/nvim/lua/config/active-theme.lua"
  local override colorscheme install_cs

  mkdir -p "$(dirname "$dest")"

  if override="$(theme_override "$id" nvim lua)"; then
    cp "$override" "$dest"
  else
    cat >"$dest" <<EOF
return {
  colorscheme = "${id}",
  install_colorscheme = false,
}
EOF
  fi
  theme_log "wrote $dest"

  colorscheme="$(
    grep -E 'colorscheme[[:space:]]*=' "$dest" | head -1 \
      | sed -E 's/.*colorscheme[[:space:]]*=[[:space:]]*"([^"]+)".*/\1/'
  )"
  install_cs="$(
    grep -E 'install_colorscheme[[:space:]]*=' "$dest" | head -1 \
      | sed -E 's/.*install_colorscheme[[:space:]]*=[[:space:]]*(true|false).*/\1/'
  )"

  if [[ "$install_cs" == "true" && -n "$colorscheme" ]]; then
    _nvim_write_colorscheme "$colorscheme"
  fi

  local sock reloaded=0
  shopt -s nullglob
  local sock_globs=(/tmp/nvim.*/0 "$HOME"/.cache/nvim/*.pipe)
  if [[ -n "${XDG_RUNTIME_DIR:-}" ]]; then
    sock_globs+=("${XDG_RUNTIME_DIR}"/nvim.*.0)
  fi
  for sock in "${sock_globs[@]}"; do
    [[ -S "$sock" ]] || continue
    if nvim --server "$sock" --remote-send "<Cmd>colorscheme ${colorscheme}<CR>" 2>/dev/null; then
      reloaded=1
    fi
  done
  shopt -u nullglob

  if [[ "$reloaded" -eq 1 ]]; then
    theme_log "updated running nvim instances"
  else
    theme_log "nvim will pick up theme on next start"
  fi
}
